// Void-and-cluster blue noise (Ulichney 1993), toroidal, deterministic.
// Usage: node scripts/gen-blue-noise.mjs  -> writes src/render/blue-noise-data.ts
import { writeFileSync } from 'node:fs';

const N = 128, n = N * N, SIGMA = 1.9, R = 8;
let seed = 20260101;
const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);

const kernel = [];
for (let dy = -R; dy <= R; dy++) for (let dx = -R; dx <= R; dx++) kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);
const E = new Float64Array(n);
const bits = new Uint8Array(n);
const splat = (i, sign) => {
  const x = i % N, y = (i / N) | 0;
  for (const [dx, dy, w] of kernel) E[((y + dy + N) % N) * N + ((x + dx + N) % N)] += sign * w;
};
const set = (i, v) => { bits[i] = v; splat(i, v ? 1 : -1); };
const tightest = () => { let b = -1, bi = -1; for (let i = 0; i < n; i++) if (bits[i] && E[i] > b) { b = E[i]; bi = i; } return bi; };
const largestVoid = () => { let b = Infinity, bi = -1; for (let i = 0; i < n; i++) if (!bits[i] && E[i] < b) { b = E[i]; bi = i; } return bi; };

// Initial pattern: ~10% ones, relaxed until stable.
const ones0 = Math.floor(n * 0.1);
for (let k = 0; k < ones0;) { const i = (rnd() * n) | 0; if (!bits[i]) { set(i, 1); k++; } }
for (let guard = 0; guard < 20000; guard++) {
  const c = tightest(); set(c, 0);
  const v = largestVoid();
  set(v, 1);
  if (v === c) break;
}
const initial = Uint8Array.from(bits);
const rank = new Int32Array(n);

// Phase 1: remove ones from tightest cluster, rank descending.
let ones = ones0;
for (let r = ones0 - 1; r >= 0; r--) { const c = tightest(); set(c, 0); rank[c] = r; }
// Phase 2: restore, then fill largest voids up to half.
bits.fill(0); E.fill(0);
for (let i = 0; i < n; i++) if (initial[i]) set(i, 1);
let r = ones0;
for (; r < n / 2; r++) { const v = largestVoid(); set(v, 1); rank[v] = r; }
// Phase 3: invert roles; tightest cluster of zeros becomes the next one.
const zerosToOnes = () => { let b = -1, bi = -1; for (let i = 0; i < n; i++) if (!bits[i] && E[i] > b) { b = E[i]; bi = i; } return bi; };
// Switch the energy map to measure the remaining zeros.
E.fill(0);
const z = new Uint8Array(n);
for (let i = 0; i < n; i++) if (!bits[i]) { z[i] = 1; splat(i, 1); }
for (; r < n; r++) {
  let b = -1, bi = -1;
  for (let i = 0; i < n; i++) if (z[i] && E[i] > b) { b = E[i]; bi = i; }
  rank[bi] = r; z[bi] = 0; splat(bi, -1);
}
void zerosToOnes; void ones;

const bytes = new Uint8Array(n);
for (let i = 0; i < n; i++) bytes[i] = Math.floor((rank[i] * 256) / n);
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync(new URL('../src/render/blue-noise-data.ts', import.meta.url),
  `// Generated by scripts/gen-blue-noise.mjs (void-and-cluster, sigma ${SIGMA}, toroidal). Do not edit.\n` +
  `export const BLUE_NOISE_SIZE = ${N};\nexport const BLUE_NOISE_B64 =\n  '${b64}';\n`);
console.log('ranks unique:', new Set(rank).size, 'of', n);
